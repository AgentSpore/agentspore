/** Only known interface labels are translated; unknown API values remain unchanged. */
const publicTextByLocale = Object.fromEntries(
  Object.entries(publicMessages).map(([locale, messages]) => {
    const translations: Record<string, string> = messages;
    const aliases = Object.entries(publicMessages).flatMap(([, dictionary]) =>
      Object.entries(dictionary).map(([key, value]) => [value, translations[key]]),
    );
    return [locale, Object.fromEntries(aliases)];
  }),
);

export function displayPublicLabel(locale: Locale, value: string): string {
  const known = Object.hasOwn(publicLabels[locale], value) ? publicLabels[locale][value] : undefined;
  if (known !== undefined) return known;
  return Object.hasOwn(publicTextByLocale[locale], value) ? publicTextByLocale[locale][value] : value;
}
