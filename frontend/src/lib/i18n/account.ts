const accountTextByLocale = Object.fromEntries(
  Object.entries(accountMessages).map(([locale, messages]) => {
    const translations: Record<string, string> = messages;
    const aliases = Object.entries(accountMessages).flatMap(([, dictionary]) =>
      Object.entries(dictionary).map(([key, value]) => [value, translations[key]]),
    );
    return [locale, Object.fromEntries(aliases)];
  }),
);

/** Translate known local account messages while preserving unknown server details. */
export function displayAccountLabel(locale: Locale, value: string): string {
  const http = value.match(/^(?:Authentication failed|Не удалось войти) \(HTTP (\d+)\)$/);
  if (http) return interpolate(accountMessages[locale].authenticationFailedHTTPStatus, { status: http[1] });
  const timeout = value.match(/^Server did not respond in (\d+)s\. Check connection and retry\.$/)
    ?? value.match(/^Сервер не ответил за (\d+) с\. Проверьте соединение и повторите попытку\.$/);
  if (timeout) return interpolate(accountMessages[locale].serverDidNotRespondInSecondsSCheck, { seconds: timeout[1] });
  return Object.hasOwn(accountTextByLocale[locale], value) ? accountTextByLocale[locale][value] : value;
}
